"""Inline every \\input{tables/...} of paper/final/main.tex into one self-contained file.

The team edits the paper in Overleaf, where updating one file is far simpler than ten.
Output: paper/final/main_overleaf.tex (paste/upload as main.tex in Overleaf).
"""
import re
from pathlib import Path

root = Path(__file__).resolve().parent.parent / "paper" / "final"
src = (root / "main.tex").read_text(encoding="utf-8")


def inline(match):
    path = root / (match.group(1) + ("" if match.group(1).endswith(".tex") else ".tex"))
    return f"% ---- {match.group(1)} (generated by scripts/make_paper_tables.py)\n" + path.read_text(encoding="utf-8").rstrip()


out = re.sub(r"\\input\{(tables/[^}]+)\}", inline, src)
assert "\\input{tables/" not in out
(root / "main_overleaf.tex").write_text(out, encoding="utf-8")
print("wrote main_overleaf.tex:", len(out), "characters")
